package com.example.motormates.ui.theme

import androidx.compose.ui.unit.dp

/**
 * Escala de espaciados de la app. Usar estos valores (y no números sueltos)
 * mantiene el mismo ritmo vertical y los mismos márgenes en todas las
 * pantallas: gutter es el margen lateral estándar de 20dp.
 */
object Spacing {
    val xxs = 4.dp
    val xs = 8.dp
    val sm = 12.dp
    val md = 16.dp
    val gutter = 20.dp
    val lg = 24.dp
    val xl = 32.dp
}

/** Radios de las esquinas, de lo más pequeño (chips) a lo más grande (portada). */
object Radius {
    val sm = 10.dp
    val md = 14.dp
    val lg = 16.dp
    val xl = 20.dp
}
